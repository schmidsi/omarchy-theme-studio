#!/usr/bin/env python3
"""Regenerate src/js/themes.js from the stock themes installed on this Omarchy system.

Colors are resolved with `omarchy-theme-color --all`, so derived keys
(dark_background, bright_*, brown, ...) match what Omarchy itself computes.
"""
import json, re, subprocess, sys
from pathlib import Path

THEMES = Path('/usr/share/omarchy/themes')
OUT = Path(__file__).resolve().parent.parent / 'src/js/themes.js'
KEYS = re.findall(r"'(\w+)'", re.search(r"const KEYS = \[(.*?)\]", (OUT.parent / 'color.js').read_text()).group(1)) + ['hyprland_active_border', 'hyprland_inactive_border']

themes = {}
for d in sorted(p for p in THEMES.iterdir() if (p / 'colors.toml').exists()):
    out = subprocess.run(['omarchy-theme-color', '--file', str(d / 'colors.toml'), '--all'],
                         capture_output=True, text=True, check=True).stdout
    vals = dict(line.split('\t', 1) for line in out.splitlines() if '\t' in line)
    mode = re.search(r'^mode\s*=\s*"(\w+)"', (d / 'colors.toml').read_text(), re.M)
    themes[d.name] = {'mode': mode.group(1) if mode else 'dark', **{k: vals[k] for k in KEYS if k in vals}}

OUT.write_text('// Generated by scripts/extract-themes.py from ' + str(THEMES) + '. Do not edit.\n'
               'const STOCK = ' + json.dumps(themes, indent=1) + ';\n')
print(f'{len(themes)} themes -> {OUT}', file=sys.stderr)
